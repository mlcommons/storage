"""SUT block cells derived from ``systems/<name>.yaml`` (v3.0 column parity).

Five of the six formerly-manual System-Under-Test cells are now generated by
reportgen from the system-description YAML instead of being filled in by hand
after the fact:

===========================  ==================================================
Final column                 Source
===========================  ==================================================
``Type``                     ``solution.capabilities.simultaneous_write`` +
                             ``simultaneous_read`` (Shared / Failover), then
                             ``architecture.storage_location``, then
                             ``architecture.product_API``
``Access Protocol``          ``architecture.benchmark_API``: file -> POSIX,
                             object -> S3
``Availability``             ``solution.availability``, title-cased for display
``Usable Capacity (TiB)``    ``solution.usable_capacity_tib``
``Integrated Client          ``solution.int_client_store_tib`` (optional field;
Storage (TiB)``              blank when absent — nobody is expected to use it
                             in v3.0, the column survives for v2.0 parity)
===========================  ==================================================

The ``Type`` string is assembled exactly as specified:

    if (simultaneous_write && simultaneous_read) Type = 'Shared'
    else                                         Type = 'Failover'
    if (storage_location == 'remote_and_local')  Type += ' remote and local'
    else                                         Type += ' ' + storage_location
    Type += ' ' + product_API

Degradation contract: a system YAML that is missing, unreadable, or lacking
the source fields leaves the derived cells blank and logs a warning — it never
raises. reportgen must keep producing tables for a tree whose YAMLs have not
yet been backfilled with the new required fields. ``Type`` in particular is
blank when ANY of its four inputs is absent, rather than emitting a
half-built string like ``Shared remote None`` (user-confirmed).
"""

from __future__ import annotations

import json
import pathlib
import shutil
from argparse import Namespace

import pytest
import yaml

from mlpstorage_py.report_generator import ReportGenerator

_REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
_FIXTURES_ROOT = _REPO_ROOT / "tests" / "fixtures" / "sample_results"


def _system_yaml(
    *,
    storage_location: str = "remote",
    benchmark_API: str = "file",
    product_API: str = "file",
    simultaneous_write: bool = True,
    simultaneous_read: bool = True,
    usable_capacity_tib: float = 512,
    availability: str = "available",
    int_client_store_tib: float | None = None,
    deployment: str | None = None,
    product_nodes: list | None = None,
    product_switches: list | None = None,
    clients: list | None = None,
    rack_power_supplies: list | None = None,
) -> dict:
    """A system-description dict carrying every field the SUT block reads."""
    solution = {
        "submission_name": "AcmeSysA",
        "friendly_description": "Acme test system",
        "architecture": {
            "storage_location": storage_location,
            "benchmark_API": benchmark_API,
            "product_API": product_API,
            "client_footprint": "open_source",
            "client_installation": "in_box",
        },
        "capabilities": {
            "multi_host": True,
            "simultaneous_write": simultaneous_write,
            "simultaneous_read": simultaneous_read,
            "remap_time_in_seconds": (
                0 if (simultaneous_write and simultaneous_read) else 30
            ),
        },
        "usable_capacity_tib": usable_capacity_tib,
        "availability": availability,
    }
    if int_client_store_tib is not None:
        solution["int_client_store_tib"] = int_client_store_tib
    sut: dict = {"solution": solution, "total_rack_units": 14}
    if deployment is not None:
        sut["deployment"] = deployment
    if product_nodes is not None:
        sut["product_nodes"] = product_nodes
    if product_switches is not None:
        sut["product_switches"] = product_switches
    if clients is not None:
        sut["clients"] = clients
    if rack_power_supplies is not None:
        sut["rack_power_supplies"] = rack_power_supplies
    return {"system_under_test": sut}


def _prepare_tree(tmp_path: pathlib.Path, sys_yaml: dict) -> pathlib.Path:
    """Copy the multi_orgname fixture, writing *sys_yaml* as acme's system."""
    dest = tmp_path / "repo_root"
    shutil.copytree(_FIXTURES_ROOT / "multi_orgname", dest)
    systems_dir = dest / "closed" / "acme" / "systems"
    systems_dir.mkdir(parents=True, exist_ok=True)
    (systems_dir / "system-a.yaml").write_text(yaml.safe_dump(sys_yaml))
    return dest


def _acme_row(root: pathlib.Path) -> dict:
    gen = ReportGenerator(str(root), args=Namespace(debug=False),
                          validate_structure=False)
    rc = gen.generate_reports()
    assert rc == 0, f"generate_reports returned {rc}"
    per_model = (root / "closed" / "acme" / "results" / "system-a"
                 / "training" / "unet3d" / "run" / "results.json")
    rows = json.loads(per_model.read_text())
    assert len(rows) == 1
    return rows[0]


