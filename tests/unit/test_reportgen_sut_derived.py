# Type + Access Protocol                                                       #
# --------------------------------------------------------------------------- #

# Every (Type, Access Protocol) pair produced by the 115 system YAMLs in the
# v3.0 submission tree, plus two shapes the schema permits but nobody
# submitted (write-capable/read-restricted, and Failover remote_and_local).
_TYPE_CASES = [
    # storage_location, product_API, benchmark_API, s_write, s_read, Type, proto
    ("remote", "file", "file", True, True, "Shared remote file", "POSIX"),
    ("remote", "object", "object", True, True, "Shared remote object", "S3"),
    ("local", "file", "file", True, True, "Shared local file", "POSIX"),
    ("remote_and_local", "file", "file", True, True,
     "Shared remote and local file", "POSIX"),
    ("remote_and_local", "object", "object", True, True,
     "Shared remote and local object", "S3"),
    ("local", "block", "file", False, False, "Failover local block", "POSIX"),
    ("remote", "file", "file", False, True, "Failover remote file", "POSIX"),
    ("remote", "block", "file", False, True, "Failover remote block", "POSIX"),
    ("remote", "file", "file", True, False, "Failover remote file", "POSIX"),
    ("remote_and_local", "block", "file", False, False,
     "Failover remote and local block", "POSIX"),
]


class TestTypeAndAccessProtocol:
    @pytest.mark.parametrize(
        "loc,prod,bench,s_write,s_read,expected_type,expected_proto",
        _TYPE_CASES,
    )
    def test_derived_type_and_protocol(
        self, tmp_path, loc, prod, bench, s_write, s_read,
        expected_type, expected_proto,
    ):
        root = _prepare_tree(tmp_path, _system_yaml(
            storage_location=loc, product_API=prod, benchmark_API=bench,
            simultaneous_write=s_write, simultaneous_read=s_read,
        ))
        row = _acme_row(root)
        assert row["Type"] == expected_type
        assert row["Access Protocol"] == expected_proto

    def test_object_type_always_pairs_with_s3(self):
        """Any Type naming 'object' must carry Access Protocol 'S3'."""
        for _loc, _prod, _bench, _sw, _sr, exp_type, exp_proto in _TYPE_CASES:
            if "object" in exp_type:
                assert exp_proto == "S3", (
                    f"case {exp_type!r} pairs with {exp_proto!r}, not S3"
                )


