_DERIVED_COLUMNS = (
    "Type", "Access Protocol", "Availability",
    "Usable Capacity (TiB)", "Integrated Client Storage (TiB)",
)


class TestDegradesGracefully:
    def test_yaml_without_new_fields_leaves_cells_blank(self, tmp_path):
        """A not-yet-backfilled YAML must not break report generation."""
        root = _prepare_tree(tmp_path, {
            "system_under_test": {
                "solution": {"submission_name": "AcmeSysA"},
                "total_rack_units": 14,
            }
        })
        row = _acme_row(root)
        for col in _DERIVED_COLUMNS:
            assert row[col] == "", f"{col} should be blank, got {row[col]!r}"
        # The rest of the block is unaffected.
        assert row["Organization"] == "acme"
        assert row["RU's"] == 14

    def test_missing_system_yaml_leaves_cells_blank(self, tmp_path):
        dest = tmp_path / "repo_root"
        shutil.copytree(_FIXTURES_ROOT / "multi_orgname", dest)
        row = _acme_row(dest)  # no systems/ dir written at all
        for col in _DERIVED_COLUMNS:
            assert row[col] == ""

    def test_unreadable_yaml_leaves_cells_blank(self, tmp_path):
        dest = tmp_path / "repo_root"
        shutil.copytree(_FIXTURES_ROOT / "multi_orgname", dest)
        systems_dir = dest / "closed" / "acme" / "systems"
        systems_dir.mkdir(parents=True, exist_ok=True)
        (systems_dir / "system-a.yaml").write_text("{[ not: valid: yaml")
        row = _acme_row(dest)
        for col in _DERIVED_COLUMNS:
            assert row[col] == ""

    @pytest.mark.parametrize("dropped", [
        "storage_location", "product_API",
    ])
    def test_missing_architecture_field_blanks_type(self, tmp_path, dropped):
        """User-confirmed: blank Type when ANY architecture input is missing,
        never a half-built string like 'Shared remote None'."""
        sys_yaml = _system_yaml()
        del sys_yaml["system_under_test"]["solution"]["architecture"][dropped]
        root = _prepare_tree(tmp_path, sys_yaml)
        assert _acme_row(root)["Type"] == ""

    @pytest.mark.parametrize("dropped", [
        "simultaneous_write", "simultaneous_read",
    ])
    def test_missing_capability_field_blanks_type(self, tmp_path, dropped):
        sys_yaml = _system_yaml()
        del sys_yaml["system_under_test"]["solution"]["capabilities"][dropped]
        root = _prepare_tree(tmp_path, sys_yaml)
        assert _acme_row(root)["Type"] == ""

    def test_missing_benchmark_api_blanks_access_protocol(self, tmp_path):
        """Access Protocol has a single input; absent means blank, NOT the
        'S3' else-branch."""
        sys_yaml = _system_yaml()
        arch = sys_yaml["system_under_test"]["solution"]["architecture"]
        del arch["benchmark_API"]
        root = _prepare_tree(tmp_path, sys_yaml)
        assert _acme_row(root)["Access Protocol"] == ""

    def test_type_and_protocol_degrade_independently(self, tmp_path):
        """Dropping a Type input must not blank Access Protocol."""
        sys_yaml = _system_yaml()
        del sys_yaml["system_under_test"]["solution"]["architecture"]["product_API"]
        root = _prepare_tree(tmp_path, sys_yaml)
        row = _acme_row(root)
        assert row["Type"] == ""
        assert row["Access Protocol"] == "POSIX"


